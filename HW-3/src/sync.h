#ifndef SYNC_H
#define SYNC_H
//-------------------------------------------------------------------------
//  семафоры POSIX, к которым обращаются по номеру
//-------------------------------------------------------------------------
//  Две реализации с одинаковым интерфейсом:
//    sync_unnamed.c - неименованные семафоры (sem_init) в разделяемой памяти;
//    sync_named.c   - именованные семафоры (sem_open) с именами /<имя>_s<номер>.
//-------------------------------------------------------------------------

#include <semaphore.h>

// Создать n семафоров с начальными значениями init[].
// mem - место в разделяемой памяти
int sync_create(const char *name, int n, const int *init, sem_t *mem);
int sync_attach(const char *name, sem_t *mem); // подключиться к готовым
void sync_remove(const char *name, int n);     // удалить (вызывает создатель)

int sync_wait(int id);    // 0 - дождались, -1 - велели завершиться, -2 - семафора нет
int sync_trywait(int id); // 0 - уменьшили, -1 - значение было 0
void sync_post(int id);

extern volatile int sync_quit; // выставляется обработчиком сигнала у рабочих процессов

#endif
