#ifndef LOG_H
#define LOG_H
//-------------------------------------------------------------------------
//  вывод событий на экран и в журнал
//-------------------------------------------------------------------------

long clock_ms(void); // монотонные часы системы, мс (общие для всех процессов)

// fd журнала (-1 - нет), тихий режим, мс на единицу времени и адреса в общей
// памяти: момент начала, время последнего события, число событий
void log_init(int log_fd, int quiet, int tick_ms, long *start, long *last, long *events);
long now_ms(void); // миллисекунды с начала моделирования
long now_t(void);  // модельное время, единицы

// Строка события: время, категория, участник, описание (как printf)
void event(const char *cat, const char *who, const char *fmt, ...);

// Текст и на экран, и в журнал
void say(const char *fmt, ...);

#endif
