#!/usr/bin/env bash
#-------------------------------------------------------------------------
#  run_independent.sh - запуск линии из независимых процессов
#  Запуск:  ./tests/run_independent.sh shm [ключи менеджера]   (разделяемая память)
#           ./tests/run_independent.sh mq  [ключи менеджера]   (очереди сообщений)
#  Пример:  ./tests/run_independent.sh mq -c configs/01_basic.cfg -d 100
#-------------------------------------------------------------------------
#  Каждый участник - отдельная программа (shm_worker / mq_worker), которая
#  запускается сама по себе. Скрипт только избавляет от ручного запуска
#  десятка программ в разных терминалах. Менеджер работает на переднем
#  плане, поэтому Ctrl+C останавливает всю линию.
#------------------------------------------------------------------------

cd "$(dirname "$0")/.." || exit 1
MODE=$1
shift
if [ "$MODE" != shm ] && [ "$MODE" != mq ]; then
    echo "Использование: $0 shm|mq [ключи менеджера]" >&2
    exit 1
fi
[ -x "bin/${MODE}_manager" ] || make >/dev/null || exit 1
NAME=${IPC_NAME:-asm_line}               # имя объектов IPC

# Какие участники нужны - спрашиваем у менеджера (ключ -L)
LIST=$("./bin/${MODE}_manager" -n "$NAME" -L "$@")
code=$?
if [ $code -ne 0 ]; then              # ошибка в данных - участников не запускаем
    echo "$LIST"
    exit $code
fi

# Участники запускаются сразу после менеджера, каждый - отдельной программой
# (если менеджер ещё не успел создать объекты IPC, участник подождёт его)
(
    sleep 0.2
    while read -r role idx; do
        "./bin/${MODE}_worker" -n "$NAME" "$role" "$idx" &
    done <<< "$LIST"
    wait
) &

"./bin/${MODE}_manager" -n "$NAME" "$@"
code=$?
wait                                     # дожидаемся завершения участников
exit $code
