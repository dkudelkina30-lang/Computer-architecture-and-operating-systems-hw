#ifndef COUNTER_H
#define COUNTER_H
//-------------------------------------------------------------------------
//  счётчик для ожидания между потоками
//-------------------------------------------------------------------------
//  Счётчик хранит неотрицательное число «разрешений»:
//    - свободных мест в накопителе,
//    - деталей, готовых к выдаче,
//    - сообщений «что-то изменилось» для роботов и сборочных постов.
//  counter_wait уменьшает число на 1, а если оно равно 0, поток ждёт.
//  counter_post увеличивает число на 1 и будит один ждущий поток.
//
//  Есть две реализации с одинаковым интерфейсом:
//    counter_sem.c - на семафорах POSIX (sem_t) -> программа line_sem
//    counter_cond.c - на мьютексе и условной переменной -> программа line_cond
//-------------------------------------------------------------------------

#include <pthread.h>
#include <semaphore.h>

typedef struct Counter
{
    sem_t sem;             // используется в версии на семафорах
    pthread_mutex_t mutex; // используются в версии на условных переменных
    pthread_cond_t cond;
    int value;
} Counter;

void counter_init(Counter *c, int value); // начальное значение
void counter_wait(Counter *c);            // взять 1, при нуле - ждать
int counter_trywait(Counter *c);          // взять 1 без ожидания: 0 - удалось, -1 - нет
void counter_post(Counter *c);            // вернуть 1 и разбудить ждущего
void counter_destroy(Counter *c);

#endif
