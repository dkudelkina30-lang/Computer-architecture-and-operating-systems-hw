#ifndef LOG_H
#define LOG_H
//-------------------------------------------------------------------------
//  вывод событий на экран и в журнал (из любых потоков)
//-------------------------------------------------------------------------

void log_init(int log_fd, int quiet, int tick_ms);  // дескриптор журнала, тихий режим, мс на единицу времени
long now_ms(void);           // миллисекунды с начала моделирования
long now_t(void);            // модельное время (единицы) с начала моделирования
long last_event_ms(void);    // когда было последнее событие (для сторожа)
long events_count(void);     // сколько всего событий выведено

// Строка события: время, категория, участник, описание 
void event(const char *cat, const char *who, const char *fmt, ...);

// Текст и на экран, и в журнал
void say(const char *fmt, ...);

#endif
