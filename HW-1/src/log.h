#ifndef LOG_H
#define LOG_H
//--------------------------------------------------------------------
//  Вывод событий на консоль и в журнал через файловые дескрипторы
//--------------------------------------------------------------------

// Настроить вывод: дескриптор журнала (-1 - без журнала), задержка после каждого события в мс
void log_init(int log_fd, int quiet, int delay_ms);

// Событие модели: время, категория, участник, описание.
// Пишется в журнал всегда, на консоль, только если не тихий режим.
void event(long t, const char *cat, const char *who, const char *fmt, ...)
    __attribute__((format(printf, 4, 5)));

// Текст и на консоль, и в журнал (итоги, сообщения)
void say(const char *fmt, ...) __attribute__((format(printf, 1, 2)));

#endif
